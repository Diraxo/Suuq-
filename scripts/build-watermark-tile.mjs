// Pre-renders the seamless "Suuqiye" watermark tile used by the scan Worker's PNG-tile fallback
// (workers/image-scan/src/cloudflare.ts, WATERMARK_MODE=tile). Run when the mark's look changes:
//   node scripts/build-watermark-tile.mjs
// Needs `sharp` (a dependency of web/). Output is committed so the Worker never depends on fonts at runtime:
//   workers/image-scan/assets/watermark-tile.png            (for eyeballing)
//   workers/image-scan/src/tile.generated.ts                 (base64 + geometry the Worker imports)
// The tile repeats seamlessly: every mark is drawn at all 9 wrap-around offsets, so nothing is cut at an edge.
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharp = createRequire(path.join(root, 'web', 'package.json'))('sharp');

export const TILE = { w: 600, h: 360, fontSize: 54, angle: -30, opacity: 0.32, text: 'Suuqiye' };
// Two marks per tile, staggered like a brick wall.
const MARKS = [[TILE.w / 4, TILE.h / 4], [(TILE.w * 3) / 4, (TILE.h * 3) / 4]];

export function tileSvg(t = TILE) {
  const parts = [];
  for (const [x, y] of MARKS) {
    for (const dx of [-t.w, 0, t.w]) {
      for (const dy of [-t.h, 0, t.h]) {
        const tf = `translate(${x + dx} ${y + dy}) rotate(${t.angle})`;
        const common = `text-anchor="middle" dominant-baseline="central" font-size="${t.fontSize}" font-weight="700" font-family="Arial, Helvetica, sans-serif" transform="${tf}"`;
        parts.push(`<text ${common} fill="none" stroke="#000" stroke-opacity="${(t.opacity * 0.6).toFixed(2)}" stroke-width="${(t.fontSize * 0.09).toFixed(1)}">${t.text}</text>`);
        parts.push(`<text ${common} fill="#fff" fill-opacity="${t.opacity}">${t.text}</text>`);
      }
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${t.w}" height="${t.h}" viewBox="0 0 ${t.w} ${t.h}">${parts.join('')}</svg>`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const png = await sharp(Buffer.from(tileSvg())).png({ compressionLevel: 9 }).toBuffer();
  const { data } = await sharp(png).raw().toBuffer({ resolveWithObject: true });
  let covered = 0;
  for (let i = 3; i < data.length; i += 4) if (data[i] > 8) covered++;
  const coverage = covered / (data.length / 4);
  if (coverage < 0.04) throw new Error(`tile has almost no mark pixels (${(coverage * 100).toFixed(1)}%) — is a font missing?`);
  fs.writeFileSync(path.join(root, 'workers/image-scan/assets/watermark-tile.png'), png);
  fs.writeFileSync(
    path.join(root, 'workers/image-scan/src/tile.generated.ts'),
    `// GENERATED by scripts/build-watermark-tile.mjs — do not edit. Seamless "${TILE.text}" tile (${TILE.w}x${TILE.h}, text ${TILE.fontSize}px, ${TILE.angle}deg, rgba).\n` +
      `export const TILE_W = ${TILE.w};\nexport const TILE_H = ${TILE.h};\nexport const TILE_FONT_SIZE = ${TILE.fontSize};\n` +
      `export const TILE_PNG_BASE64 = '${png.toString('base64')}';\n`,
  );
  console.log(`tile ${TILE.w}x${TILE.h}, ${png.length} bytes, ${(coverage * 100).toFixed(1)}% mark pixels`);
}
